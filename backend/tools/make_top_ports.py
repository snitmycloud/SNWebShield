"""Generate backend/app/data/top_ports.py from a LOCAL copy of Nmap's `nmap-services` file.

This is a one-off developer tool. The application never downloads anything at runtime.

    python tools/make_top_ports.py <path-to-nmap-services> app/data/top_ports.py

The top 1,000 TCP ports are the 1,000 with the highest open-frequency in `nmap-services`, which is how
Nmap's `--top-ports 1000` (its default scan) chooses them. Ports with equal frequency keep file order.
"""
import re
import sys
from pathlib import Path

LINE = re.compile(r"^(\S+)\s+(\d+)/tcp\s+([0-9.eE+-]+)")
HEADER = '''"""The fixed list of the 1,000 most commonly open TCP ports, and names for them.

Generated by tools/make_top_ports.py from Nmap's `nmap-services` (https://github.com/nmap/nmap), which is
(C) 1996-2025 Insecure.Com LLC and distributed under the Nmap Public Source License
(https://svn.nmap.org/nmap/LICENSE). Only port numbers, service names and their order are used here.
Do not edit by hand; regenerate with the tool. The application never downloads this at runtime.
"""
'''


def main(source: str, target: str) -> None:
    ranked = {}
    order = []
    for line in Path(source).read_text(encoding="utf-8", errors="replace").splitlines():
        match = LINE.match(line)
        if not match:
            continue
        name, port, freq = match.group(1), int(match.group(2)), float(match.group(3))
        if 1 <= port <= 65535 and port not in ranked:
            ranked[port] = (name, freq)
            order.append(port)
    top = sorted(order, key=lambda p: -ranked[p][1])[:1000]  # stable: ties keep file order
    assert len(top) == 1000 and len(set(top)) == 1000
    names = {p: ranked[p][0] for p in sorted(set(top))}
    tie = ranked[sorted(order, key=lambda p: -ranked[p][1])[999]][1] == ranked[sorted(order, key=lambda p: -ranked[p][1])[1000]][1]
    body = HEADER
    body += f"\nCUTOFF_FREQUENCY_TIE = {tie!r}  # True if the 1000th and 1001st ports share a frequency\n"
    body += "\nTOP_TCP_PORTS = (\n"
    for i in range(0, 1000, 12):
        body += "    " + ", ".join(str(p) for p in top[i:i + 12]) + ",\n"
    body += ")\n\nSERVICE_NAMES = {\n"
    for port, name in names.items():
        body += f"    {port}: {name!r},\n"
    body += "}\n"
    Path(target).write_text(body, encoding="utf-8")
    print(f"wrote {target}: 1000 ports, tie at cutoff: {tie}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
